"""Synthetic stress test for posterior adaptive self-consistency.

Run from the repository root:

    python experiments/adaptive_consistency_synthetic.py

The script writes a compact Markdown report to ``reports/adaptive-consistency.md``.
"""

from __future__ import annotations

import sys
from pathlib import Path
from textwrap import dedent

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ulm_ml.adaptive_consistency import (  # noqa: E402
    evaluate_policy,
    fixed_budget_rule,
    format_metrics_table,
    posterior_confidence_rule,
    sample_answer_streams,
    synthetic_answer_distributions,
    vote_margin_rule,
)
from ulm_ml.paths import PROJECT_ROOT  # noqa: E402

REPORT_PATH = PROJECT_ROOT / "reports" / "adaptive-consistency.md"


def build_report(
    seed: int = 7,
    num_tasks: int = 2_500,
    num_answers: int = 5,
    max_samples: int = 32,
) -> str:
    rng = np.random.default_rng(seed)
    distributions = synthetic_answer_distributions(
        num_tasks=num_tasks,
        num_answers=num_answers,
        rng=rng,
    )
    streams = sample_answer_streams(distributions, max_samples=max_samples, rng=rng)

    policies = [
        ("fixed-8", lambda: fixed_budget_rule(8)),
        ("fixed-16", lambda: fixed_budget_rule(16)),
        ("fixed-32", lambda: fixed_budget_rule(32)),
        ("margin-3", lambda: vote_margin_rule(min_samples=4, margin=3, max_samples=32)),
        (
            "posterior-0.90",
            lambda: posterior_confidence_rule(
                min_samples=4,
                confidence=0.90,
                max_samples=32,
                draws=1024,
                seed=seed,
            ),
        ),
        (
            "posterior-0.95",
            lambda: posterior_confidence_rule(
                min_samples=4,
                confidence=0.95,
                max_samples=32,
                draws=1024,
                seed=seed + 1,
            ),
        ),
    ]
    metrics = [evaluate_policy(name, streams, factory) for name, factory in policies]

    fixed_32 = next(item for item in metrics if item.name == "fixed-32")
    posterior_95 = next(item for item in metrics if item.name == "posterior-0.95")
    saved = 1.0 - posterior_95.mean_samples / fixed_32.mean_samples
    delta = posterior_95.accuracy - fixed_32.accuracy

    setup = dedent(
        f"""\
        # Adaptive Posterior Self-Consistency: Synthetic Note

        Generated by `experiments/adaptive_consistency_synthetic.py` with seed `{seed}`
        on `{num_tasks}` synthetic tasks, `{num_answers}` answer classes, and a hard cap
        of `{max_samples}` samples per task.

        ## Setup

        Each task is represented by a categorical answer sampler, standing in for a
        stochastic chain-of-thought decoder whose final answer is extracted and normalized.
        Answer `0` is the ground-truth answer.  The synthetic suite mixes easy, medium,
        and ambiguous tasks so that a compute policy must decide when the current
        majority answer is stable and when additional samples are still valuable.

        ## Result
        """
    )
    conclusion = dedent(
        f"""\

        The posterior-0.95 policy uses {posterior_95.mean_samples:.2f} samples on average,
        saving {saved:.1%} of samples versus fixed-32 while changing accuracy by
        {delta:+.3f}.  The important qualitative result is not that this toy simulator
        proves a benchmark win; it shows that a tiny Bayesian stability test can be used
        as a cheap gate before spending real LLM calls.

        ## Proposed next real experiment

        1. Collect answer-only traces from a small open reasoning model on GSM8K or SVAMP
           with 32 stochastic samples per problem.
        2. Replay the exact same traces through these policies, so every policy sees
           identical candidate generations.
        3. Calibrate the posterior confidence threshold on a held-out split to target a
           maximum accuracy drop, then report sample savings on the test split.
        4. Compare against fixed-N self-consistency, vote-margin early stopping, and any
           model-provided confidence if available.
        """
    )
    return f"{setup}\n{format_metrics_table(metrics)}\n{conclusion}"

def main() -> None:
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(build_report(), encoding="utf-8")
    print(f"wrote {REPORT_PATH.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
